"""
generate_lineage.py — Regenerate FEATURE_LINEAGE.md from features/schema.py (spec-derived
source / computation / default / rationale) and feature_store/registry.db (one entry per
registered version: parameters, version rationale, transform summary, parquet_path).

Never hand-edit FEATURE_LINEAGE.md; rerun this instead:
    python scripts/generate_lineage.py
"""

from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import pandas as pd

from feature_store import store
from features import schema
from scripts.build_training_features import TRAINING_AS_OF


def snapshot_facts(parquet_path: str, feature: str) -> str:
    path = store.resolve_parquet_path(parquet_path)
    if not os.path.exists(path):
        return "**MISSING ON DISK**"
    df = pd.read_parquet(path)
    as_of = df["as_of_date"].dropna().unique()
    as_of_text = ", ".join(map(str, as_of)) if len(as_of) else "not recorded (legacy snapshot, see ARTIFACT_NOTES.md)"
    return f"{len(df)} rows, column `{feature}` ({df[feature].dtype}), as_of_date: {as_of_text}"


def main():
    os.chdir(ROOT)  # data/ and feature_store/ paths are repo-relative
    versioned = {vf.name: vf for vf in schema.VERSIONED_FEATURES}
    lines = [
        "# Feature Lineage",
        "",
        "Generated by `scripts/generate_lineage.py` from `features/schema.py` (spec-derived definitions) "
        "and `feature_store/registry.db` table `feature_registry` (one entry per registered version). "
        "Do not edit by hand — rerun the script.",
        "",
        f"Feature-set version: {schema.FEATURE_SET_VERSION}. Training as_of (default of "
        f"`scripts/build_training_features.py`): {TRAINING_AS_OF}.",
        "",
        "**Rules shared by every feature** (from `feature_spec.md`):",
        "- Only rows of `data/transactions.db:transactions` with `txn_timestamp < as_of` are read; only customers "
        "in `data/customers.csv` with `signup_date < as_of` are in the population.",
        "- `data/transactions_monthly_agg.parquet` is not read by any feature (behind the transactions table for "
        "July 2026, missing 10 customers).",
        "- `last_txn` = the customer's last transaction of any kind (returned or not) before as_of. "
        "\"Last 3 months\" = (last_txn − 90 days, last_txn]. Previous period = [signup_date, last_txn − 90 days]. "
        "A month = 30 days. Spend = sum of `amount` where `is_returned = 0`.",
        "- `churned` is the label and is never an input.",
        "",
    ]
    for spec in schema.FEATURES:
        versions = store.list_versions(spec.name).sort_values("version")
        lines += [
            f"## `{spec.name}`",
            "",
            f"- **Sources:** {', '.join(f'`{s}`' for s in spec.sources)}",
            f"- **Computation:** {spec.computation}",
            f"- **Zero-activity default:** {spec.zero_activity_default}",
            f"- **Output dtype / nullable:** {spec.dtype} / {spec.nullable}",
            f"- **Business rationale:** {spec.rationale}",
        ]
        if spec.name in versioned:
            vf = versioned[spec.name]
            plan = "; ".join(f"v{i + 1} = {json.dumps(v.parameters)}" for i, v in enumerate(vf.versions))
            lines.append(f"- **Versioned on `{vf.parameter}`** (feature_spec.md): {plan}")
        lines += ["", f"Registered versions ({len(versions)}):", ""]
        if versions.empty:
            lines += ["_None registered — run scripts/build_training_features.py._", ""]
        for _, row in versions.iterrows():
            lines += [
                f"### `{spec.name}` v{int(row['version'])}{' (latest)' if row['is_latest'] else ''}",
                "",
                f"- **Parameters:** `{row['parameters']}`",
                f"- **Registered:** {row['created_at']}",
                f"- **Registry source_columns:** {row['source_columns']}",
                f"- **Transform (registry):** {row['transform_summary']}",
                f"- **Why this version (registry):** {row['business_rationale']}",
                f"- **Feature-store location:** `feature_store/registry.db` → `feature_registry` "
                f"(feature_name = '{spec.name}', version = {int(row['version'])}); "
                f"parquet_path = `{row['parquet_path']}`",
                f"- **Snapshot:** {snapshot_facts(row['parquet_path'], spec.name)}",
                "",
            ]
    unknown = sorted(set(store.list_feature_names()) - {f.name for f in schema.FEATURES})
    if unknown:
        lines += ["## Registered but not in schema", "", *[f"- `{n}`" for n in unknown], ""]
    with open("FEATURE_LINEAGE.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("Wrote FEATURE_LINEAGE.md")


if __name__ == "__main__":
    main()
